-- Whether each glyph is major or minor, and what spell it casts.
--
-- Blizzard's profile API says neither: a character's glyphs arrive as a name
-- and a glyph id, three major and three minor shuffled together, and one name
-- -- Glyph of Stampede -- exists as both, so nothing can be keyed on the name.
-- There is no glyph endpoint either; /data/wow/glyph 404s under every
-- namespace, exactly as the talent tree does.
--
-- This is the game's own GlyphProperties table for build 5.5.4.67732, read from
-- wago.tools, which publishes the client's DB2 files. Preferred to a website's
-- glyph pages because it is the same data the client itself reads, and to an
-- in-game harvest because the client lists only the class being played -- that
-- would have meant a character of every class.
--
-- The file numbers major as 0 and minor as 1; the client's own GetGlyphInfo
-- numbers them 1 and 2. Checked before converting rather than assumed: six
-- glyphs whose type this client had already reported -- Animal Bond, Explosive
-- Trap and Solace major, Revive Pet, Cheetah and Stampede minor -- agree at an
-- offset of exactly one, all six.
--
-- A third value, 2, appears on 4 rows: the prime glyph type Cataclysm had and
-- Mists removed. Nobody on either ladder wears one, so they are left out.
--
-- The spell is here because the glyph hyperlink cannot be trusted to describe a
-- glyph. Hovering a mage's minor Rapid Teleportation produced a tooltip headed
-- "Major Glyph", and it still did when the link was handed the real type rather
-- than a zero. So the panel states the type itself, from the table above, and
-- takes the words from the spell.
--
-- Harvested 2026-08-23. It describes the game rather than the ladder, so it needs
-- rebuilding only if Blizzard changes a glyph.

